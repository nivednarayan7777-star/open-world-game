export function getDistrict(id) {
  return DISTRICTS.find((d) => d.id === id) || DISTRICTS[6];
}

export function roadsFor(d) {
  const nodes = [{ x: d.start.x, z: d.start.z }, ...d.places];
  const main = [...nodes].sort((a, b) => a.x - b.x).map((p) => [p.x, p.z]);
  const north = nodes.filter((p) => p.z > 28).sort((a, b) => a.z - b.z).map((p) => [p.x, p.z]);
  const south = nodes.filter((p) => p.z < -40).sort((a, b) => a.x - b.x).map((p) => [p.x, p.z]);
  const roads = [main];
  if (north.length >= 2) roads.push(north);
  if (south.length >= 2) roads.push(south);
  return roads;
}
